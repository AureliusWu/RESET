HAN = re.compile(r"[\u3400-\u9fff]")

def total_han():
    return sum(len(HAN.findall(line.get("text", ""))) for data in all_data.values() for scene in data.get("scenes", []) for line in scene.get("lines", []))

def scene_map(name):
    return {s["id"]: s for s in all_data[name].get("scenes", [])}

