# Candidate scenes remain within PR B scope. Add concrete, one-off details only to narration lines.
for key, details in banks.items():
    candidates = []
    for sid in (f"c4_{key}_1", f"c4_{key}_2", f"end_{key}"):
        scene = scenes.get(sid)
        if scene:
            candidates.extend([line for line in scene.get("lines", []) if line.get("speaker") == "旁白"])
    di = 0
    for line in candidates:
        if total_han() >= 81600 or di >= len(details):
            break
        add = details[di]
        di += 1
        base = line.get("text", "").rstrip("。！？")
        candidate = base + "。" + add
        if len(candidate) <= 80:
            line["text"] = candidate

